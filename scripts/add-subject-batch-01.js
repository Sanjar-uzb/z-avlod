function appendBatch(filePath, level, baseMap, batchMap) {
  const data = JSON.parse(fs.readFileSync(filePath, "utf8"));

  for (const [subject, questions] of Object.entries(batchMap)) {
    const startId = baseMap[subject] + 11;
    const endId = baseMap[subject] + 20;

    for (let id = startId; id <= endId; id += 1) {
      const index = data.findIndex((item) => item.id === id);
      if (index !== -1) data.splice(index, 1);
    }

    questions.forEach((item, idx) => {
      data.push({
        id: startId + idx,
        subject,
        level,
        ...item,
      });
    });
  }

  data.sort((a, b) => a.id - b.id);
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n");
}

